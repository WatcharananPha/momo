window.i18n = {
    lang: localStorage.getItem('momo_lang') || 'th',
    t: function(key) {
        return translations[this.lang][key] || key;
    },
    setLang: function(newLang) {
        this.lang = newLang;
        localStorage.setItem('momo_lang', newLang);
        this.updateUI();
    },
    updateUI: function() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (el.tagName === 'INPUT') {
                el.placeholder = this.t(key);
            } else {
                el.textContent = this.t(key);
            }
        });
        // Trigger specific re-renders
        if (window.updateDashboardData) updateDashboardData();
        if (window.updateLangSwitcherUI) updateLangSwitcherUI();
        if (window.setGreeting) setGreeting();
    }
};
